def _slugify(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip().lower()).strip("-")
    return value or "program"


def _config_dir(settings) -> Path:  # noqa: ANN001
    return Path(settings.config_dir)


def _write_env_overlay(settings, updates: dict[str, str]) -> Path:  # noqa: ANN001
    """Write a small env overlay that docker-compose / the app can source."""
    path = Path("data/setup.env")
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by the DeSlop setup wizard. Safe to edit."]
    existing: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, _, v = line.partition("=")
                existing[k.strip()] = v.strip()
    existing.update(updates)
    for k, v in existing.items():
        lines.append(f"{k}={v}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


@router.get("/setup", response_class=HTMLResponse)
def setup_page(request: Request) -> Response:
    if is_setup_complete(request.app.state.settings):
        return RedirectResponse(url="/dashboard", status_code=303)
    settings = get_settings()
    state = load_state(settings)
    registry = request.app.state.registry
    return templates.TemplateResponse(
        request,
        "setup.html",
        {
            "state": state,
            "programs": list(registry),
            "config_dir": str(_config_dir(settings)),
            "llm_provider": settings.llm_provider,
            "oob_base_url": settings.oob_base_url,
            "active": "",
        },
    )


@router.post("/setup")
def run_setup(
    request: Request,
    admin_user: str = Form("admin"),
    admin_password: str = Form(...),
    program_name: str = Form(...),
    program_id: str = Form(""),
    in_scope: str = Form(...),
    staging_base_url: str = Form(...),
    llm_provider: str = Form("none"),
    llm_model: str = Form(""),
    oob_base_url: str = Form("http://localhost:8080"),
    enable_status_page: str | None = Form(None),
    overwrite_program: str | None = Form(None),
) -> RedirectResponse:
    _ensure_setup_open(request)
    settings = request.app.state.settings
    notes: list[str] = []

    pid = (program_id or _slugify(program_name)).strip()
    cfg_dir = _config_dir(settings)
    cfg_dir.mkdir(parents=True, exist_ok=True)
    program_path = cfg_dir / f"{pid}.yaml"

    if program_path.exists() and not overwrite_program:
        notes.append(f"program file {program_path.name} already existed; left unchanged")
    else:
        from ..config.schema import normalize_host_pattern

        program = dict(_PROGRAM_TEMPLATE)
        program["id"] = pid
        program["name"] = program_name
        scope_value = normalize_host_pattern(in_scope)
        if not scope_value:
            scope_value = "example.com"
            notes.append("in_scope input had no usable host; wrote example.com — edit the program YAML")
        scope_kind = "wildcard" if scope_value.startswith("*.") else "domain"
        program["in_scope"] = [{"kind": scope_kind, "value": scope_value}]
        program["staging"] = {
            "base_url": staging_base_url.strip(),
            "host_map": {},
        }
        program["status_page"] = {
            "enabled": bool(enable_status_page),
            "token_ttl": "P90D",
        }
        # The egress allowlist covers staging-side infrastructure, derived from
        # the staging base URL — never the (production) scope hosts.
        staging_host = normalize_host_pattern(staging_base_url)
        program["allowed_egress_hosts"] = [staging_host] if staging_host else []
        program_path.write_text(yaml.safe_dump(program, sort_keys=False), encoding="utf-8")
        notes.append(f"wrote program config {program_path}")
        # Validate it parses before declaring success.
        try:
            load_program_file(program_path)
        except ConfigError as exc:  # pragma: no cover - defensive
            notes.append(f"warning: generated config did not validate: {exc}")

    # Persist admin account + LLM/OOB settings.
    admin = admin_user.strip() or "admin"
    pw_hash = hash_password(admin_password)
    _write_env_overlay(
        settings,
        {
            "DESLOP_DASHBOARD_USER": admin,
            "DESLOP_DASHBOARD_PASSWORD_HASH": pw_hash,
            "DESLOP_LLM_PROVIDER": llm_provider,
            "DESLOP_LLM_MODEL": llm_model.strip(),
            "DESLOP_OOB_BASE_URL": oob_base_url.strip(),
            "DESLOP_CONFIG_DIR": str(cfg_dir),
        },
    )
    if llm_provider == "none":
        notes.append("LLM disabled: reports without a raw HTTP request will need manual review.")

    # Apply in-process so the running app reflects the new settings immediately.
    settings.dashboard_user = admin
    settings.dashboard_password_hash = pw_hash
    settings.llm_provider = llm_provider  # type: ignore[assignment]
    settings.llm_model = llm_model.strip()

    try:
        init_db(settings)
    except Exception as exc:  # noqa: BLE001
        notes.append(f"database init reported: {exc}")

    # (Re)load programs so the new program is live.
    from ..config.loader import ProgramRegistry

    try:
        request.app.state.registry = ProgramRegistry.from_dir(cfg_dir)
    except ConfigError as exc:
        notes.append(f"registry reload issue: {exc}")

    mark_complete(
        admin_user=settings.dashboard_user,
        programs=[pid],
        llm_provider=llm_provider,
        notes=notes,
        settings=settings,
    )
    return RedirectResponse(url="/setup/done", status_code=303)


@router.get("/setup/done", response_class=HTMLResponse)
def setup_done(request: Request) -> HTMLResponse:
    settings = get_settings()
    state = load_state(settings)
    return templates.TemplateResponse(
        request, "setup_done.html", {"state": state, "active": ""}
    )


@router.get("/setup/db-check")
def db_check(request: Request) -> dict:
    """Lightweight connectivity probe the wizard calls to validate the database."""
    _ensure_setup_open(request)
    settings = get_settings()
    try:
        engine = make_engine(settings)
        with engine.connect() as conn:
            from sqlalchemy import text

            conn.execute(text("SELECT 1"))
        return {"ok": True, "dialect": engine.dialect.name}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "error": str(exc)}
